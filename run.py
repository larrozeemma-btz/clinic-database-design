"""Build the clinic database and run every query.

Usage:
    python run.py            # builds clinic.db, prints results, writes docs/results.md
"""
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).parent
SQL = ROOT / "sql"
DB_PATH = ROOT / "clinic.db"


def build(db_path=DB_PATH):
    """Create a fresh database from the schema and seed files."""
    if isinstance(db_path, Path) and db_path.exists():
        db_path.unlink()
    conn = sqlite3.connect(db_path)
    conn.execute("PRAGMA foreign_keys = ON")
    conn.executescript((SQL / "01_schema.sql").read_text())
    conn.executescript((SQL / "02_seed.sql").read_text())
    return conn


def named_queries():
    """Split 03_queries.sql into (name, sql) pairs using the '-- name:' markers."""
    text = (SQL / "03_queries.sql").read_text()
    parts = re.split(r"^-- name: (.+)$", text, flags=re.M)
    return [(parts[i].strip(), parts[i + 1].strip()) for i in range(1, len(parts), 2)]


def to_markdown(columns, rows):
    head = "| " + " | ".join(columns) + " |"
    rule = "|" + "|".join("---" for _ in columns) + "|"
    body = ["| " + " | ".join("" if v is None else str(v) for v in row) + " |" for row in rows]
    return "\n".join([head, rule, *body])


def main():
    conn = build()
    out = ["# Query results", "", "Generated by `python run.py` from the seed data in `sql/02_seed.sql`.", ""]
    for name, sql in named_queries():
        cur = conn.execute(sql)
        columns = [c[0] for c in cur.description]
        rows = cur.fetchall()
        table = to_markdown(columns, rows)
        print(f"\n## {name}\n{table}")
        out += [f"## {name}", "", table, ""]
    (ROOT / "docs" / "results.md").write_text("\n".join(out))
    conn.close()


if __name__ == "__main__":
    main()
